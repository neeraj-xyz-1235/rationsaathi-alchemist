"""Plain PDFs (receipt and monthly report) with fpdf2's built-in fonts.

Built-in fonts only cover Latin-1, so any other script (Hindi/Marathi names) prints as '?'.
Embedding a Devanagari TTF font is the fix if that matters."""
from datetime import datetime, timezone

from fpdf import FPDF

GREEN = (31, 107, 69)
GREY = (110, 120, 112)


def _t(s) -> str:
    return str(s if s is not None else "").encode("latin-1", "replace").decode("latin-1")


class _Doc(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(*GREEN)
        self.cell(0, 10, "RationSaathi", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(*GREEN)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(4)
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*GREY)
        self.cell(0, 8, _t("Generated by RationSaathi, an independent tool. The official scheme "
                           "rules and the competent authority remain the source of truth."),
                  align="C")


def _kv(pdf: _Doc, key: str, value: str):
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*GREY)
    pdf.cell(48, 7, _t(key))
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(0, 7, _t(value), new_x="LMARGIN", new_y="NEXT")


def receipt_pdf(w: dict, household: dict) -> bytes:
    pdf = _Doc()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, "Withdrawal receipt", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    _kv(pdf, "Receipt ID", w["receipt_id"])
    _kv(pdf, "Verification code", w["verification_code"])
    _kv(pdf, "Item", w["item"])
    _kv(pdf, "Quantity", f'{w["quantity"]} {w["unit"]}')
    _kv(pdf, "Withdrawal date", w["withdrawal_date"])
    _kv(pdf, "Shop receipt ref.", w.get("reference") or "-")
    _kv(pdf, "Household head", household["head_name"])
    _kv(pdf, "Location", f'{household["district"]}, {household["state"]}')
    _kv(pdf, "Shop receipt photo", {"verified": "Checked: matches this entry", "mismatch": "Checked: does not match",
                                    "unreadable": "Could not be read"}.get(w.get("proof_status"), "Not attached"))
    pdf.ln(6)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*GREY)
    pdf.multi_cell(0, 5, _t("To check this receipt, open RationSaathi > Withdrawals > Verify a "
                            "receipt and enter the receipt ID or verification code."))
    return bytes(pdf.output())


def report_pdf(r: dict) -> bytes:
    pdf = _Doc()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, _t(f'Monthly ration report - {r["period_label"]}'), new_x="LMARGIN",
             new_y="NEXT")
    pdf.ln(2)
    hh = r["household"]
    _kv(pdf, "Household head", hh["head_name"])
    _kv(pdf, "Location", f'{hh["district"]}, {hh["state"]}')
    _kv(pdf, "Members", str(hh["members"]))
    _kv(pdf, "Scheme", r["scheme_name"])
    pdf.ln(4)

    def row(cells, widths, bold=False, fill=False):
        pdf.set_font("Helvetica", "B" if bold else "", 10)
        if fill:
            pdf.set_fill_color(234, 245, 236)
        for text, wd in zip(cells, widths):
            pdf.cell(wd, 8, _t(text), border="B", fill=fill)
        pdf.ln()

    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 9, "Allocation and balance", new_x="LMARGIN", new_y="NEXT")
    widths = [50, 35, 35, 35, 25]
    row(["Item", "Allocated", "Withdrawn", "Remaining", "Over by"], widths, True, True)
    for i in r["items"]:
        row([i["item"], f'{i["allocated"]} kg', f'{i["withdrawn"]} kg',
             f'{i["remaining"]} kg', f'{i["over_by"]} kg'], widths)
    pdf.ln(6)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 9, "Withdrawals", new_x="LMARGIN", new_y="NEXT")
    if not r["withdrawals"]:
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 8, "No withdrawals recorded this month.", new_x="LMARGIN", new_y="NEXT")
    else:
        widths = [30, 35, 30, 70]
        row(["Date", "Item", "Quantity", "Receipt ID"], widths, True, True)
        for w in r["withdrawals"]:
            row([w["date"], w["item"], f'{w["quantity"]} kg', w["receipt_id"]], widths)
    pdf.ln(6)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*GREY)
    note = ("Quantities are the allocation worked out from the household card category and size, "
            "minus the withdrawals recorded in RationSaathi.")
    if r["scheme_assumed"]:
        note += " The card category was not confirmed, so Priority Household figures were assumed."
    pdf.multi_cell(0, 5, _t(note))
    pdf.cell(0, 6, _t("Generated " + datetime.now(timezone.utc).strftime("%d %b %Y %H:%M UTC")))
    return bytes(pdf.output())
